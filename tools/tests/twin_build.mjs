// Builds tools/research/step3_twin.py: the "Same thing in Python Keras" panels of Step 3, in order, after a preamble that
// recreates the Step 1-2 notebook state (X, y, idx_train, idx_val, p_val). Run it with real TensorFlow to prove the twins train.
import fs from 'fs'; import path from 'path'; import { fileURLToPath } from 'url'; import { loadSteps } from './seed.mjs';
const here = path.dirname(fileURLToPath(import.meta.url));
const { ctx } = loadSteps();
const pre = `# PanelGuard Steps 3-4 — the Python Keras twin of every JavaScript cell, run end to end (generated by tools/tests/twin_build.mjs).
# Preamble = the Step 1-2 notebook state: X, y, idx_train, idx_val (Step 1) and p_val (Step 2 baseline scores).
import os, json, time
os.environ['TF_CPP_MIN_LOG_LEVEL'] = '3'
import numpy as np
import keras
from sklearn.model_selection import train_test_split
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
X = np.fromfile(os.path.join(ROOT, 'tools/ref/cells64.u8'), dtype=np.uint8).reshape(2624, 64, 64)
rows = json.load(open(os.path.join(ROOT, 'site/data/labels.json')))['rows']
prob = np.array([r[1] for r in rows]); kind = np.array([r[2] for r in rows]); y = (prob >= 0.5).astype(int)
idx = np.arange(len(y))
idx_train, idx_rest = train_test_split(idx, test_size=0.4, stratify=y, random_state=42)
idx_val, idx_test = train_test_split(idx_rest, test_size=0.5, stratify=y[idx_rest], random_state=42)
p_val = np.load(os.path.join(ROOT, 'tools/research/svc_val.npy'))   # Step 2 SVC validation scores (same pipeline as 2a/2b)
keras.utils.set_random_seed(int(os.environ.get('SEED', '0')))
T0 = time.time()
`;
const cells = [...ctx.PG_STEP3.substeps, ...ctx.PG_STEP4.substeps].filter((s) => s.twin).map((s) => `\n# ===== ${s.id} ${s.name} =====\n` + s.twin);
const post = `\nprint('TOTAL seconds', round(time.time() - T0))\nprint(json.dumps({"best_epoch": best_epoch, "cnn_auc": round(float(best_auc), 3), "cnn_far": round(false_alarm_at_95(y_val, p_cnn), 3), "svc_far": round(false_alarm_at_95(y_val, p_svc), 3), "blend_w": best_w, "blend_far": round(best_far, 3), "low": float(low), "high": float(high), "person_per_1000": round(1000 * float(person.mean())), "def_passed": int((auto_pass & (y_val == 1)).sum())}))\n`;
fs.writeFileSync(path.resolve(here, '../research/step34_twin.py'), pre + cells.join('\n') + post);
console.log('wrote tools/research/step34_twin.py with', cells.length, 'cells');
